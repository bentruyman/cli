import type { CommandData } from "./types";

function quote(value: string): string {
  return `'${value.replace(/'/g, "'\\''")}'`;
}

/** Uses Bash's own completion variables; no bash-completion package is required. */
export function generateBashCompletions(data: CommandData): string {
  const func = `_${data.name.replace(/[^a-zA-Z0-9_]/g, "_")}_completions`;
  const nodes: CommandData[] = [];
  const visit = (node: CommandData) => {
    nodes.push(node);
    node.subcommands.filter((sub) => !sub.hidden).forEach(visit);
  };
  visit(data);
  const lines = [
    `# Bash completions for ${data.name}`,
    "# Generated by @truyman/cli",
    `${func}() {`,
    '  local cur="${COMP_WORDS[COMP_CWORD]}" word context=0 skip=0 operand=0 i j short',
    "  COMPREPLY=()",
    "  for ((i=1; i<COMP_CWORD; i++)); do",
    '    word="${COMP_WORDS[i]}"',
    "    if ((skip)); then skip=0; continue; fi",
    '    [[ "$word" == -- ]] && return',
    '    [[ "$word" == --*=* ]] && continue',
    '    case "$context:$word" in',
  ];
  for (const [id, node] of nodes.entries()) {
    for (const opt of node.options.filter((opt) => opt.type !== "boolean")) {
      const names = [`${id}:--${opt.long}`, ...(opt.short ? [`${id}:-${opt.short}`] : [])];
      lines.push(`      ${names.join("|")}) skip=1; continue ;;`);
    }
    for (const sub of node.subcommands.filter((sub) => !sub.hidden)) {
      const names = [sub.name, ...(sub.aliases ?? [])].map((name) => `${id}:${name}`);
      lines.push(
        `      ${names.join("|")}) if ((!operand)); then context=${nodes.indexOf(sub)}; continue; fi ;;`,
      );
    }
  }
  lines.push(
    "    esac",
    '    if [[ "$word" == -?* && "$word" != --* ]]; then',
    "      for ((j=1; j<${#word}; j++)); do",
    '        short="${word:j:1}"',
    '        case "$context:$short" in',
  );
  for (const [id, node] of nodes.entries()) {
    for (const opt of node.options.filter((opt) => opt.type !== "boolean" && opt.short)) {
      lines.push(
        `          ${id}:${opt.short}) if ((j == \${#word}-1)); then skip=1; fi; break ;;`,
      );
    }
  }
  lines.push(
    "        esac",
    "      done",
    "    fi",
    '    [[ "$word" != -* || "$word" == - ]] && operand=1',
    "  done",
    "  ((skip)) && return",
    '  local commands="" opts=""',
    '  case "$context" in',
  );
  for (const [id, node] of nodes.entries()) {
    const commands = node.subcommands
      .filter((sub) => !sub.hidden)
      .flatMap((sub) => [sub.name, ...(sub.aliases ?? [])]);
    const opts = [
      "--help",
      "-h",
      "--version",
      "-V",
      ...node.options.flatMap((opt) => [
        `--${opt.long}`,
        ...(opt.short ? [`-${opt.short}`] : []),
        ...(opt.negatable ? [`--no-${opt.long}`] : []),
      ]),
    ];
    lines.push(
      `    ${id}) commands=${quote(commands.join(" "))}; opts=${quote(opts.join(" "))} ;;`,
    );
  }
  lines.push(
    "  esac",
    '  if [[ "$cur" == -* ]]; then',
    '    while IFS= read -r word; do COMPREPLY+=("$word"); done < <(compgen -W "$opts" -- "$cur")',
    '  elif ((!operand)) && [[ -n "$commands" ]]; then',
    '    while IFS= read -r word; do COMPREPLY+=("$word"); done < <(compgen -W "$commands" -- "$cur")',
    "  fi",
    "}",
    `complete -F ${func} ${data.name}`,
  );
  return lines.join("\n");
}
