import type { CommandData } from "./types.js";

function escapeFish(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

/** Track the command path, excluding option values and honoring aliases. */
export function generateFishCompletions(data: CommandData): string {
  const func = `__${data.name.replace(/[^a-zA-Z0-9_]/g, "_")}_context`;
  const nodes: CommandData[] = [];
  const visit = (node: CommandData) => {
    nodes.push(node);
    node.subcommands.filter((sub) => !sub.hidden).forEach(visit);
  };
  visit(data);
  const lines = [
    `# Fish completions for ${data.name}`,
    "# Generated by @truyman/cli",
    `# Save to ~/.config/fish/completions/${data.name}.fish`,
    `complete -c ${data.name} -f`,
    `function ${func}`,
    "  set -l context 0",
    "  set -l skip 0",
    "  set -l operand 0",
    "  set -l words (commandline -opc)",
    "  for word in $words[2..-1]",
    "    if test $skip = 1; set skip 0; continue; end",
    '    if test "$word" = --; echo "$context:2"; return; end',
    "    if string match -q -- '--*=*' $word; continue; end",
    '    switch "$context:$word"',
  ];
  for (const [id, node] of nodes.entries()) {
    for (const opt of node.options.filter((opt) => opt.type !== "boolean")) {
      const names = [`${id}:--${opt.long}`, ...(opt.short ? [`${id}:-${opt.short}`] : [])];
      lines.push(`      case ${names.join(" ")}`, "        set skip 1; continue");
    }
    for (const sub of node.subcommands.filter((sub) => !sub.hidden)) {
      const names = [sub.name, ...(sub.aliases ?? [])].map((name) => `${id}:${name}`);
      lines.push(
        `      case ${names.join(" ")}`,
        `        if test $operand = 0; set context ${nodes.indexOf(sub)}; continue; end`,
      );
    }
  }
  lines.push(
    "    end",
    "    if string match -qr -- '^-[^-]' $word",
    "      for j in (seq 2 (string length -- $word))",
    "        set -l short (string sub -s $j -l 1 -- $word)",
    '        switch "$context:$short"',
  );
  for (const [id, node] of nodes.entries()) {
    for (const opt of node.options.filter((opt) => opt.type !== "boolean" && opt.short)) {
      lines.push(
        `          case ${id}:${opt.short}`,
        "            if test $j = (string length -- $word); set skip 1; end",
        "            break",
      );
    }
  }
  lines.push(
    "        end",
    "      end",
    "    end",
    "    if not string match -q -- '-*' $word; or test \"$word\" = -; set operand 1; end",
    "  end",
    '  echo "$context:$operand"',
    "end",
    "",
  );
  for (const [id, node] of nodes.entries()) {
    const condition = `-n 'contains -- (${func}) ${id}:0 ${id}:1'`;
    const prefix = `complete -c ${data.name} ${condition}`;
    lines.push(
      `${prefix} -s h -l help -d 'Show help'`,
      `${prefix} -s V -l version -d 'Show version'`,
    );
    for (const opt of node.options) {
      const short = opt.short ? `-s ${opt.short} ` : "";
      const value = opt.type !== "boolean" ? " -r" : "";
      const desc = opt.description ? ` -d '${escapeFish(opt.description)}'` : "";
      lines.push(`${prefix} ${short}-l ${opt.long}${value}${desc}`);
      if (opt.negatable) lines.push(`${prefix} -l no-${opt.long}`);
    }
    for (const sub of node.subcommands.filter((sub) => !sub.hidden)) {
      const desc = sub.description ? ` -d '${escapeFish(sub.description)}'` : "";
      for (const name of [sub.name, ...(sub.aliases ?? [])]) {
        lines.push(`complete -c ${data.name} -n 'test (${func}) = ${id}:0' -a ${name}${desc}`);
      }
    }
  }
  return lines.join("\n");
}
